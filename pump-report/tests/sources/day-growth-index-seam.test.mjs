import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createPumpSources, SOURCE_HTTP_PLAN} from '../../sources/index.mjs';
import {DAY_WINDOW_MS} from '../../sources/day-growth.mjs';
const root=new URL('../../../',import.meta.url),expiry=1792938197470;
test('J source index exposes independent one-GET day window and coverage without altering core121',async()=>{
  assert(Date.now()<expiry);globalThis.fetch=()=>{throw Error('J_SEAM_OFFLINE_NO_NETWORK');};
  const reg=JSON.parse(await fs.readFile(new URL('pump-report/sources/registry-curated13-native-relative-v1.json',root),'utf8'));
  const btc=reg.instruments.find(e=>e.instrument.base==='BTC'),eth=reg.instruments.find(e=>e.instrument.base==='ETH');
  const end=Math.floor(Date.now()/60000)*60000,start=end-DAY_WINDOW_MS,at=end+5000,calls=[];
  const body={code:0,data:Array.from({length:1440},(_,i)=>({time:start+i*60000,open:'100',high:'102',low:'99',close:'101'}))};
  const source=createPumpSources({identityRegistry:[btc],clock:()=>at,broker:{async request(r){calls.push(r);
    const query=new URL(r.url).searchParams;
    const data=query.get('limit')==='1440'?body:{code:0,data:Array.from({length:121},(_,i)=>({time:end-121*60000+i*60000,open:'100',high:'102',low:'99',close:'101',volume:'10'}))};
    return {ok:true,status:200,data,received_ts:end+1000,receipt_id:'SYNTHETIC_J_SEAM_'+calls.length,cache_hit:false};}}});
  assert.equal(typeof source.getDayGrowth,'function');assert.equal(calls.length,0,'lazy day loader must not issue constructor IO');
  assert.equal(SOURCE_HTTP_PLAN.day_growth_per_window_max,1);assert.equal(SOURCE_HTTP_PLAN.core,3);assert.equal(SOURCE_HTTP_PLAN.core_price_fallback_max,1);
  const day=await source.getDayGrowth({instrument:btc.instrument});
  assert.equal(calls.length,1);assert.equal(day.facts.growth_24h.status,'USABLE');assert.equal(day.facts.growth_24h.unit,'USDT_CLOSED_ROLLING_24H');
  assert.equal(day.facts.growth_24h.event_ts,end);assert.equal(day.facts.growth_24h.received_ts,end+1000);assert.equal(day.facts.growth_24h.expires_ts,end+90000);
  assert.equal(calls[0].purpose,'CORE');assert.equal(calls[0].candidate_id,btc.instrument.instrument_id);
  assert.equal(new URL(calls[0].url).searchParams.get('endTime'),String(end-1));
  let coverage=source.getCoverage();assert.equal(coverage.totals.day_growth_checked,1);assert.equal(coverage.totals.day_growth_usable,1);
  assert.equal(coverage.totals.core_checked,0);assert.equal(coverage.totals.core_usable,0);
  assert.equal(coverage.instruments[0].growth_24h.window_start,start);assert.equal(coverage.instruments[0].growth_24h.window_end,end);
  assert.deepEqual(coverage.instruments[0].growth_24h.receipt_ids,['SYNTHETIC_J_SEAM_1']);
  assert.equal(coverage.expense_ledger,'ROOT_BROKER_ONLY');assert.equal(coverage.actual_SQL_cost,null);assert.equal(coverage.actual_provider_cost,null);
  coverage.instruments[0].growth_24h.window_end=1;assert.equal(source.getCoverage().instruments[0].growth_24h.window_end,end,'coverage must be detached');
  await assert.rejects(()=>source.getDayGrowth({instrument:eth.instrument}),e=>e.code==='INDEPENDENT_REGISTRY_IDENTITY_MISMATCH');
  assert.equal(calls.length,1,'unregistered instrument must fail before broker');
  await source.getDayGrowth({instrument:btc.instrument,force_refresh:true});assert.equal(calls.length,2);assert.equal(calls[1].ttl_ms,0);
  const core=await source.getCore({instrument:btc.instrument,only_facts:['candles']});
  assert.equal(calls.length,3);assert.equal(new URL(calls[2].url).searchParams.get('limit'),'121');
  assert.equal(new URL(calls[2].url).searchParams.get('endTime'),String(end));
  assert.equal(core.facts.candles.unit,'OHLC_USDT_NATIVE_REPORTED_QUANTITY');
  assert.equal(core.facts.growth_24h,undefined,'day request must remain explicit and separate');
  assert.equal(core.facts.candles.value.length,121);assert.equal(core.facts.candles.value[0].volume_base,null);
  const unknown=structuredClone(btc);unknown.qualifications.candles={};let deniedCalls=0;
  const denied=createPumpSources({identityRegistry:[unknown],clock:()=>at,broker:{async request(){deniedCalls++;throw Error('NO_IO_EXPECTED');}}});
  const result=await denied.getDayGrowth({instrument:btc.instrument});assert.equal(result.facts.growth_24h.status,'NOT_CHECKED');
  assert.equal(result.facts.growth_24h.value,null);assert.equal(deniedCalls,0);
  assert.equal(denied.getCoverage().totals.day_growth_checked,0);assert.equal(denied.getCoverage().totals.day_growth_usable,0);
  assert(Date.now()<expiry);
});
