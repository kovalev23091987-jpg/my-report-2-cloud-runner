import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createDayGrowthLoader, parseDayGrowth, DAY_GROWTH_UNIT, DAY_WINDOW_MS} from '../../sources/day-growth.mjs';
import {createNativeRelativeCandleQualification} from '../../sources/native-relative-qualification.mjs';
import {GROWTH_24H_UNIT, GROWTH_24H_WINDOW_MS} from '../../contracts/index.mjs';
const root=new URL('../../../',import.meta.url),expiry=1792938331213;
test('J1440 closed day: exact bounds, complete qualified OHLC grid, broker one GET, no quantity or clock drift',async()=>{
  assert(Date.now()<expiry);globalThis.fetch=()=>{throw Error('OFFLINE_ONLY_NO_NATIVE_OR_PRIVATE_IO');};
  assert.equal(DAY_GROWTH_UNIT,GROWTH_24H_UNIT);assert.equal(DAY_WINDOW_MS,GROWTH_24H_WINDOW_MS);
  // ROOT captured E and lifted the index hold; its exact prior bytes are
  // retained separately in the J seam handoff. Wire parser and factory stay frozen.
  for(const [path,expected] of [['pump-report/sources/bingx.mjs','48c68cc9b7937b4c5f8ace8cbdf029a51d00b74c7aae038be695449f3d96aaec'],
    ['pump-report/sources/native-relative-qualification.mjs','c9ab4bd23cf10376a3abd7b66490679121362286efdc82ed95d19fdf29ca753f']])
    assert.equal(createHash('sha256').update(await fs.readFile(new URL(path,root))).digest('hex'),expected,path+' must stay frozen');
  const reg=JSON.parse(await fs.readFile(new URL('pump-report/sources/registry-curated13-native-relative-v1.json',root),'utf8'));
  const entry=reg.instruments.find(e=>e.instrument.base==='BTC'),instrument=entry.instrument,qualification=entry.qualifications.candles;
  assert.deepEqual(qualification,createNativeRelativeCandleQualification(instrument));
  const end=Math.floor(Date.now()/60000)*60000,start=end-DAY_WINDOW_MS,at=end+5000;
  const body={code:0,data:Array.from({length:1440},(_,i)=>({time:start+i*60000,open:'100',high:'102',low:'99',close:'101'}))};
  const opts={instrument,qualification,start_ts:start,end_ts:end,received_ts:end+1000};
  const parsed=parseDayGrowth({...body,data:[...body.data].reverse()},opts);
  assert.equal(parsed.qualified,true);assert.equal(parsed.value.open,100);assert.equal(parsed.value.last,101);
  assert.deepEqual(parsed.value,{open:100,last:101,start_ts:start,end_ts:end,window_ms:86400000});
  assert.equal(parsed.event_ts,end);assert.equal(parsed.coverage.included_closed_rows,1440);
  assert.equal(parsed.coverage.quantity_used,false);assert.equal(parsed.coverage.absolute_quantity,null);
  assert.equal(parsed.coverage.time_basis,'CCXT_CONSUMER_OPEN_TIME');
  const invalidVolume={...body,data:body.data.map((r,i)=>({...r,volume:i%2?'garbage':null}))};
  assert.deepEqual(parseDayGrowth(invalidVolume,opts).value,parsed.value,'price window must not depend on quantity');
  for(const missing of [0,719,1439]){
    const p=parseDayGrowth({...body,data:body.data.filter((_,i)=>i!==missing)},opts);
    assert.equal(p.value,null);assert.equal(p.event_ts,null);assert.equal(p.qualified,false);
    assert.equal(p.coverage.complete,false);assert.equal(p.coverage.gaps.length,1);
    assert.equal(p.reason,missing===719?'DAY_WINDOW_GRID_INCOMPLETE':'DAY_WINDOW_BOUNDARY_MISSING');
  }
  const unclosed=parseDayGrowth(body,{...opts,received_ts:end-1});
  assert.equal(unclosed.value,null);assert.equal(unclosed.coverage.captured_unclosed_rows,1);
  assert.equal(unclosed.reason,'DAY_WINDOW_BOUNDARY_MISSING');
  const badQ=structuredClone(qualification);badQ.volume.comparison_key+='other';
  assert.equal(parseDayGrowth(body,{...opts,qualification:badQ}).value,null);
  assert.equal(parseDayGrowth(body,{...opts,qualification:{}}).reason,'DAY_TIME_OR_IDENTITY_QUALIFICATION_REQUIRED');
  assert.throws(()=>parseDayGrowth(body,{...opts,start_ts:start+1}),e=>e.code==='DAY_EXACT_1440_MINUTE_WINDOW_REQUIRED');
  const duplicate=structuredClone(body);duplicate.data[900]=duplicate.data[899];
  assert.throws(()=>parseDayGrowth(duplicate,opts),e=>e.code==='DAY_DUPLICATE_CANDLE_TIME');
  const offGrid=structuredClone(body);offGrid.data[300].time++;
  assert.throws(()=>parseDayGrowth(offGrid,opts),e=>e.code==='DAY_CANDLE_OHLC_OR_TIME_INVALID');
  const future=structuredClone(body);future.data[300].time=end+60000;
  assert.throws(()=>parseDayGrowth(future,opts),e=>e.code==='DAY_CANDLE_OHLC_OR_TIME_INVALID');
  assert.throws(()=>parseDayGrowth({...body,data:[...body.data,{...body.data[0],time:end}]},opts),e=>e.code==='DAY_BOUNDED_OBJECT_CANDLES_REQUIRED');
  const shifted=parseDayGrowth({...body,data:body.data.map(r=>({...r,time:r.time+60000}))},{...opts,received_ts:end+60000});
  assert.equal(shifted.value,null);assert.equal(shifted.reason,'DAY_WINDOW_BOUNDARY_MISSING');
  const requests=[];let current=at;
  const response={ok:true,status:200,data:body,received_ts:end+1000,receipt_id:'SYNTHETIC_J1440_RECEIPT',cache_hit:true};
  const source=createDayGrowthLoader({clock:()=>current,resolveEntry:()=>structuredClone(entry),broker:{async request(r){requests.push(r);return structuredClone(response);}}});
  const result=await source.getDayGrowth({instrument});
  assert.equal(requests.length,1);const r=requests[0],url=new URL(r.url);
  assert.equal(url.origin,'https://open-api.bingx.com');assert.equal(url.pathname,'/openApi/swap/v3/quote/klines');
  assert.deepEqual(Object.fromEntries(url.searchParams),{endTime:String(end-1),interval:'1m',limit:'1440',startTime:String(start),symbol:'BTC-USDT'});
  assert.equal(r.provider,'BINGX');assert.equal(r.family,'USDT_M');assert.equal(r.purpose,'CORE');
  assert.equal(r.candidate_id,instrument.instrument_id);assert.equal(r.method,'GET');assert.equal(r.timeout_ms,10000);
  assert.equal(r.ttl_ms,90000);assert.deepEqual(r.estimated_cost,{http:1});
  const f=result.facts.growth_24h;assert.equal(f.status,'USABLE');assert.equal(f.kind,'growth_24h');assert.equal(f.unit,DAY_GROWTH_UNIT);
  assert.equal(f.event_ts,end);assert.equal(f.received_ts,end+1000);assert.equal(f.expires_ts,end+90000);
  assert.equal(f.origin,'OBSERVED');assert.equal(f.cache_hit,true);assert.equal(f.derived_from.original_receipt_id,response.receipt_id);
  assert.equal(f.derived_from.original_received_ts,end+1000);assert.equal(f.derived_from.absolute_quantity,null);
  assert.deepEqual(f.value,parsed.value);
  await source.getDayGrowth({instrument,force_refresh:true});assert.equal(requests.length,2);assert.equal(requests[1].ttl_ms,0);
  assert.equal(requests[1].cache_key,requests[0].cache_key);
  const delayed=createDayGrowthLoader({clock:()=>current,resolveEntry:()=>entry,broker:{async request(r){requests.push(r);current=end+100000;return structuredClone(response);}}});
  current=at;const old=await delayed.getDayGrowth({instrument});
  assert.equal(old.facts.growth_24h.status,'STALE');assert.equal(old.facts.growth_24h.expires_ts,end+90000);
  assert.equal(old.facts.growth_24h.event_ts,end);assert.equal(old.facts.growth_24h.received_ts,end+1000);
  assert.equal(old.coverage.window_end,end,'window must not drift during await');
  let deniedCalls=0;current=at;
  const unqualifiedEntry=structuredClone(entry);unqualifiedEntry.qualifications.candles={};
  const denied=createDayGrowthLoader({clock:()=>current,resolveEntry:()=>unqualifiedEntry,broker:{async request(){deniedCalls++;}}});
  const absent=await denied.getDayGrowth({instrument});assert.equal(absent.facts.growth_24h.status,'NOT_CHECKED');
  assert.equal(absent.facts.growth_24h.value,null);assert.equal(deniedCalls,0);
  const wrong=createDayGrowthLoader({clock:()=>current,resolveEntry:()=>reg.instruments.find(e=>e.instrument.base==='ETH'),broker:{async request(){deniedCalls++;}}});
  await assert.rejects(()=>wrong.getDayGrowth({instrument}),e=>e.code==='DAY_INDEPENDENT_REGISTRY_IDENTITY_MISMATCH');assert.equal(deniedCalls,0);
  let failedCalls=0;
  const blocked=createDayGrowthLoader({clock:()=>current,resolveEntry:()=>entry,broker:{async request(){failedCalls++;throw Object.assign(Error('budget'),{code:'PROTECTED_DAY_RESERVE'});}}});
  const refusal=await blocked.getDayGrowth({instrument});assert.equal(refusal.facts.growth_24h.status,'NOT_CHECKED');
  assert.equal(refusal.facts.growth_24h.value,null);assert.equal(failedCalls,1,'no fallback or retry');
  const incomplete=createDayGrowthLoader({clock:()=>current,resolveEntry:()=>entry,broker:{async request(){return {...response,data:{...body,data:body.data.slice(1)}};}}});
  assert.equal((await incomplete.getDayGrowth({instrument})).facts.growth_24h.value,null);
  assert(Date.now()<expiry);
});
