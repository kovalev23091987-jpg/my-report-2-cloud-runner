import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const root=process.argv[2]?path.resolve(process.argv[2],'src'):path.resolve('current-generation/files/src');
const {consumeBlockResultContext,auditRenderedBlockResults}=await import(pathToFileURL(path.join(root,'block-result-context.mjs')));
const {formatManualReport}=await import(pathToFileURL(path.join(root,'manual-report-formatter.mjs')));
const {BLOCKS}=await import(pathToFileURL(path.join(root,'evidence-v2.mjs')));
const fixture=JSON.parse(fs.readFileSync('checkpoints/btw-preserved-block-result-input-20261004.json'));
const canonical=structuredClone(fixture.canonical),scoreBefore=JSON.stringify(canonical.metadata.supplemental_score_adjustment);
const context=consumeBlockResultContext({contract:canonical.metadata.contract,now:canonical.observed_ts,evidence:canonical.metadata.internal_market_context.evidence_v2.evidence});
canonical.metadata.supporting_context={facts:context.facts};
const manual=formatManualReport(canonical),proof=auditRenderedBlockResults({canonical,manual});
assert.equal(manual.ok,true);assert.deepEqual(proof.used_context_block_ids.sort(),['N05','N09','N12']);
assert.equal(JSON.stringify(canonical.metadata.supplemental_score_adjustment),scoreBefore);
assert.equal(Object.keys(BLOCKS).length,11);
for(const id of ['N01','N04','N06','N13','N14','N17'])assert.equal(BLOCKS[id],undefined);
console.log(JSON.stringify({status:'EXACT_HISTORICAL_INPUT_REACHES_EXISTING_CONTEXT',provenance:fixture.source,context,proof,score_unchanged:true,active_blocks:Object.keys(BLOCKS),source_http:0,production_writes:0,telegram_calls:0,current_market_acceptance:false},null,2));
